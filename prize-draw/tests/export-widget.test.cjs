const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
(async () => {
 const html = fs.readFileSync(path.join(__dirname, '../prize-export.html'));
 const server = http.createServer((req,res) => {res.writeHead(200, {'Content-Type':'text/html;charset=utf-8'});res.end(html);});
 await new Promise(r => server.listen(0,'127.0.0.1',r));
 const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || (fs.existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined),args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:360,height:740},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:'+server.address().port);
 assert.equal(await page.locator('#download').isDisabled(),true);
 const csv='\ufeff"등수","경품명"\r\n"1등","테스트 경품"\r\n';
 await page.evaluate(csv=>window.postMessage({type:'export',csv,count:1,round:2,generatedAt:'2026-10-19 22:00:00 KST',filename:'prize-winners-R2.csv'},'*'),csv);
 await page.locator('#download:enabled').waitFor();
 assert.match(await page.locator('#summary').textContent(),/R2.*1건/);
 const event=page.waitForEvent('download');await page.locator('#download').click();const download=await event;
 assert.equal(download.suggestedFilename(),'prize-winners-R2.csv');
 assert.equal(fs.readFileSync(await download.path(),'utf8'),csv);
 await page.locator('#copy').click();
 assert.match(await page.locator('#status').textContent(),/복사|선택/);
 assert.equal(await page.locator('#csv').inputValue(),csv.replace(/\r\n/g,'\n'));
 assert.equal(await page.locator('.card').evaluate(e=>e.getBoundingClientRect().right<=innerWidth),true);
 assert.deepEqual(errors,[]);
 await browser.close();server.close();console.log('Export widget checks passed: CSV file download, UTF-8 BOM, filename, copy fallback, mobile width.');
})().catch(e=>{console.error(e);process.exit(1);});
